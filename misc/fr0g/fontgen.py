#!/usr/bin/env python3
"""fr0gOS: make an LVGL 8 bitmap font (bpp 4) from a TTF/OTF with PIL, optionally slanted (italic by shear).
usage: fontgen.py <ttf> <px> <name> <out.c> [--shear 0.2] [--chars "0123456789"]"""
import argparse
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("ttf"); ap.add_argument("px", type=int); ap.add_argument("name"); ap.add_argument("out")
ap.add_argument("--shear", type=float, default=0.0)
ap.add_argument("--first", type=int, default=32); ap.add_argument("--last", type=int, default=122)
a = ap.parse_args()
font = ImageFont.truetype(a.ttf, a.px)
asc, desc = font.getmetrics()
pad = a.px
codes = list(range(a.first, a.last + 1))
bitmap = bytearray(); dscs = []
for c in codes:
    ch = chr(c)
    W, H = a.px * 3, a.px * 3
    im = Image.new("L", (W, H), 0)
    base_y = pad + asc
    ImageDraw.Draw(im).text((pad, base_y), ch, font=font, fill=255, anchor="ls")
    if a.shear:
        # x' = x + shear*(base_y - y): tops lean right, baseline fixed
        im = im.transform((W, H), Image.AFFINE, (1, a.shear, -a.shear * base_y, 0, 1, 0), Image.BICUBIC)
    adv = font.getlength(ch)
    bb = im.getbbox()
    if not bb:
        dscs.append((len(bitmap), int(round(adv * 16)), 0, 0, 0, 0)); continue
    x0, y0, x1, y1 = bb
    g = im.crop(bb); w, h = g.size
    px = g.load(); nib = []
    for y in range(h):
        for x in range(w):
            nib.append(px[x, y] >> 4)
    if len(nib) % 2: nib.append(0)
    idx = len(bitmap)
    for i in range(0, len(nib), 2):
        bitmap.append((nib[i] << 4) | nib[i + 1])
    dscs.append((idx, int(round(adv * 16)), w, h, x0 - pad, base_y - y1))
lh = asc + desc
with open(a.out, "w") as f:
    N = a.name
    f.write(f"// Generated by misc/fr0g/fontgen.py from {a.ttf.split('/')[-1]} {a.px}px shear {a.shear} - do not edit.\n")
    f.write('#include "lvgl/lvgl.h"\n\nstatic LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {\n')
    for i in range(0, len(bitmap), 24):
        f.write("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 24]) + ",\n")
    if not bitmap: f.write("    0x00,\n")
    f.write("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},\n")
    for d in dscs:
        f.write("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},\n" % d)
    f.write("};\n\nstatic const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
    f.write(f"    {{.range_start = {codes[0]}, .range_length = {len(codes)}, .glyph_id_start = 1, .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}\n}};\n\n")
    f.write("static lv_font_fmt_txt_glyph_cache_t cache;\nstatic const lv_font_fmt_txt_dsc_t font_dsc = {\n    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,\n    .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0, .cache = &cache};\n\n")
    f.write(f"const lv_font_t {N} = {{\n    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n    .line_height = {lh}, .base_line = {desc}, .subpx = LV_FONT_SUBPX_NONE, .underline_position = -2, .underline_thickness = 1,\n    .dsc = &font_dsc}};\n")
print(a.name, len(codes), "glyphs", len(bitmap), "bytes")
