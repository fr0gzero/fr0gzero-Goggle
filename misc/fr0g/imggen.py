#!/usr/bin/env python3
"""fr0gOS: frog frames + heart as LVGL 8 TRUE_COLOR_ALPHA images (32-bit: B, G, R, A). usage: imggen.py <frog_dir> <out.c>"""
import math, sys
from PIL import Image, ImageDraw
FROG_DIR, OUT = sys.argv[1:3]
NAMES = ["idle", "blink", "blinkH", "glanceL", "glanceR", "glanceU", "glanceD", "grin", "exclgrin", "hurt", "ko", "pumped", "dizzy"]
FILES = {"idle": "01", "glanceL": "02", "glanceR": "03", "blink": "04", "grin": "05", "exclgrin": "06", "hurt": "07", "ko": "08",
         "blinkH": "10", "glanceU": "11", "glanceD": "12", "dizzy": "14", "pumped": "15"}
WIDTH = 210
ims = {n: Image.open(f"{FROG_DIR}/frame_{FILES[n]}_{n}.png").convert("RGBA") for n in NAMES}
size = max(i.size for i in ims.values())
box = None
for n, i in ims.items():
    c = Image.new("RGBA", size, (0, 0, 0, 0)); c.alpha_composite(i, ((size[0] - i.width) // 2, (size[1] - i.height) // 2)); ims[n] = c
    bb = c.getbbox(); box = bb if box is None else (min(box[0], bb[0]), min(box[1], bb[1]), max(box[2], bb[2]), max(box[3], bb[3]))
out = ['// Generated by misc/fr0g/imggen.py - do not edit.\n#include "lvgl/lvgl.h"\n']
def emit(name, im):
    w, h = im.size; px = im.load(); data = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            data += [b, g, r, a]
    out.append(f"static const uint8_t {name}_map[] = {{\n")
    for i in range(0, len(data), 32):
        out.append("    " + ",".join(str(v) for v in data[i:i + 32]) + ",\n")
    out.append("};\n")
    out.append(f"const lv_img_dsc_t {name} = {{.header.always_zero = 0, .header.w = {w}, .header.h = {h}, .data_size = {len(data)}, "
               f".header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .data = {name}_map}};\n\n")
for n in NAMES:
    c = ims[n].crop(box)
    c = c.resize((WIDTH, round(c.height * WIDTH / c.width)), Image.LANCZOS)
    emit(f"fr0g_frog_{n}", c)
# heart, white (recoloured at runtime), 4x supersampled
S, R = 48, 4
big = Image.new("L", (S * R, S * R), 0); d = ImageDraw.Draw(big); pts = []
for i in range(200):
    t = i / 200 * 2 * math.pi
    x = 16 * math.sin(t) ** 3; y = 13 * math.cos(t) - 5 * math.cos(2 * t) - 2 * math.cos(3 * t) - math.cos(4 * t)
    pts.append((S * R / 2 + x * S * R / 36, S * R / 2 - y * S * R / 36 - S * R * 0.04))
d.polygon(pts, fill=255)
a = big.resize((S, S), Image.LANCZOS)
h = Image.new("RGBA", (S, S), (255, 255, 255, 0)); h.putalpha(a)
emit("fr0g_heart", h)
open(OUT, "w").write("".join(out))
print("frog", WIDTH, "x", round((box[3]-box[1]) * WIDTH / (box[2]-box[0])), "frames", len(NAMES))
